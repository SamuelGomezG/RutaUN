package co.edu.unal.rutaun.normativa;

/** Tipo del alcance de una norma (glosario, «Alcance»; diseño de clases, «Enums»). */
public enum TipoAlcance {
  /** Todos los programas de pregrado de la Sede, salvo las exclusiones. */
  TODOS,
  /** Los programas de una o varias facultades, salvo las exclusiones. */
  FACULTADES,
  /** Uno o varios programas concretos, salvo las exclusiones. */
  PROGRAMAS
}
